"""Generate crates/mocha-engine/src/pdf/metrics.rs from ReportLab's own font data.

Reads ReportLab (the legacy venv) so every number is exactly what ReportLab uses:
  * glyph widths of Helvetica, Helvetica-Bold, Symbol and ZapfDingbats per byte value
    (reportlab.pdfbase.pdfmetrics Font.widths, built from the AFM data in _fontdata);
  * ascent / descent of the faces;
  * the Unicode -> byte maps of ReportLab's WinAnsiEncoding, SymbolEncoding and
    ZapfDingbatsEncoding codecs (what unicode2T1 uses to pick a font per character);
  * the PDFDocEncoding map used for the document Info strings.

Usage: legacy/.venv/bin/python tools/metrics/gen_metrics.py
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "crates" / "mocha-engine" / "src" / "pdf" / "metrics.rs"

import reportlab  # noqa: E402
from reportlab.pdfbase import pdfdoc  # noqa: E402,F401  (registers the pdfdoc codec)
from reportlab.pdfbase import pdfmetrics  # noqa: E402

FONTS = [
    ("HELVETICA", "Helvetica"),
    ("HELVETICA_BOLD", "Helvetica-Bold"),
    ("SYMBOL", "Symbol"),
    ("ZAPF_DINGBATS", "ZapfDingbats"),
]


def encoding_map(codec: str) -> list[tuple[int, int]]:
    out = []
    for cp in range(0x10000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        try:
            b = chr(cp).encode(codec)
        except (UnicodeEncodeError, LookupError):
            continue
        if len(b) == 1:
            out.append((cp, b[0]))
    return out


def table(name: str, pairs: list[tuple[int, int]]) -> str:
    body = ", ".join(f"(0x{cp:04X}, 0x{b:02X})" for cp, b in pairs)
    lines = [f"pub static {name}: [(u32, u8); {len(pairs)}] = ["]
    row = []
    for i, (cp, b) in enumerate(pairs):
        row.append(f"(0x{cp:04X}, 0x{b:02X})")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    return "\n".join(lines)


def main() -> None:
    parts = [
        "// @generated by tools/metrics/gen_metrics.py from ReportLab "
        f"{reportlab.Version} (legacy/.venv). DO NOT EDIT BY HAND.\n"
        "// Regenerate: legacy/.venv/bin/python tools/metrics/gen_metrics.py\n"
        "//\n"
        "// Data mirrored from ReportLab: Font.widths (pdfbase/pdfmetrics.py, built from\n"
        "// pdfbase/_fontdata*.py), face ascent/descent, and the Unicode -> byte codecs of\n"
        "// WinAnsiEncoding / SymbolEncoding / ZapfDingbatsEncoding used by unicode2T1.\n"
        "#![allow(clippy::unreadable_literal)]\n"
    ]
    for const, name in FONTS:
        font = pdfmetrics.getFont(name)
        widths = list(font.widths)
        assert len(widths) == 256
        rows = []
        for i in range(0, 256, 16):
            rows.append("    " + ", ".join(str(w) for w in widths[i:i + 16]) + ",")
        parts.append(f"/// Glyph widths (1/1000 em) of `{name}`, indexed by byte value.\npub static {const}_WIDTHS: [u16; 256] = [\n" + "\n".join(rows) + "\n];")
        parts.append(f"/// Face ascent (1/1000 em) of `{name}`.\npub const {const}_ASCENT: i32 = {font.face.ascent};")
        parts.append(f"/// Face descent (1/1000 em, negative) of `{name}`.\npub const {const}_DESCENT: i32 = {font.face.descent};")
    parts.append("/// Unicode scalar -> byte, ReportLab `WinAnsiEncoding` (sorted by scalar).\n"
                 + table("WINANSI", encoding_map("WinAnsiEncoding")))
    parts.append("/// Unicode scalar -> byte, ReportLab `SymbolEncoding` (sorted by scalar).\n"
                 + table("SYMBOL_ENC", encoding_map("SymbolEncoding")))
    parts.append("/// Unicode scalar -> byte, ReportLab `ZapfDingbatsEncoding` (sorted by scalar).\n"
                 + table("ZAPF_ENC", encoding_map("ZapfDingbatsEncoding")))
    parts.append("/// Unicode scalar -> byte, ReportLab `pdfdoc` codec (PDFDocEncoding; Info strings).\n"
                 + table("PDFDOC", encoding_map("pdfdoc")))
    OUT.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    sys.exit(main())
